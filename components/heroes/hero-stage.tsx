'use client';
import dynamic from 'next/dynamic';
import type {HeroId} from '@/lib/heroes';
const Atelier=dynamic(()=>import('./atelier-hero'),{ssr:false});
const Diorama=dynamic(()=>import('./diorama-hero'),{ssr:false});
const Arcadia=dynamic(()=>import('./arcadia-hero'),{ssr:false});
const Aster=dynamic(()=>import('./aster-hero'),{ssr:false});
const Solace=dynamic(()=>import('./solace-hero'),{ssr:false});
const Noema=dynamic(()=>import('./cinematic-heroes').then(module=>module.NoemaHero),{ssr:false});
const Aevora=dynamic(()=>import('./cinematic-heroes').then(module=>module.AevoraHero),{ssr:false});
const Florra=dynamic(()=>import('./creative-heroes').then(module=>module.FlorraHero),{ssr:false});
const Sprig=dynamic(()=>import('./creative-heroes').then(module=>module.SprigHero),{ssr:false});
const Sway=dynamic(()=>import('./creative-heroes').then(module=>module.SwayHero),{ssr:false});
const KineticNebula=dynamic(()=>import('./kinetic-nebula-hero'),{ssr:false});
const Luminary=dynamic(()=>import('./luminary-hero'),{ssr:false});
const ZenithBeam=dynamic(()=>import('./zenith-beam-hero'),{ssr:false});
const BioTerrain=dynamic(()=>import('./bio-terrain-hero'),{ssr:false});
export default function HeroStage({id,paused=false}:{id:HeroId;paused?:boolean}){
 if(id==='bio-terrain')return <BioTerrain paused={paused}/>;
 if(id==='zenith-beam')return <ZenithBeam paused={paused}/>;
 if(id==='kinetic-nebula')return <KineticNebula paused={paused}/>;
 if(id==='luminary')return <Luminary paused={paused}/>;
 if(id==='noema')return <Noema paused={paused}/>;
 if(id==='aevora')return <Aevora paused={paused}/>;
 if(id==='florra')return <Florra paused={paused}/>;
 if(id==='sprig')return <Sprig paused={paused}/>;
 if(id==='sway')return <Sway paused={paused}/>;
 if(id==='pavilion'||(id as string)==='atelier')return <Atelier paused={paused}/>;
 if(id==='diorama')return <Diorama paused={paused}/>;
 if(id==='aster')return <Aster paused={paused}/>;
 if(id==='arcadia')return <Arcadia paused={paused}/>;
 return <Solace paused={paused}/>;
}
